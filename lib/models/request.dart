/// Request model for chat completions.
library;

import 'package:ai_capo/models/response_format.dart';
import 'package:ai_capo/models/tool.dart';

/// The options of a chat completion request.
///
/// Only [model] is required; every other parameter is optional and is
/// forwarded to the provider when set. Parameters that a provider does not
/// support are ignored by that provider.
///
/// ```dart
/// const request = ChatCompletionRequest(
///   model: 'gpt-5-mini-2025-08-07',
///   temperature: 0.7,
///   maxTokens: 500,
/// );
/// ```
class ChatCompletionRequest {
  /// The identifier of the model to use, for example `gpt-5-mini-2025-08-07`.
  final String model;

  /// Controls randomness; higher values make the output more random.
  final double? temperature;

  /// The maximum number of tokens to generate.
  ///
  /// Falls back to [AIConfig.defaultMaxTokens] when not set.
  final int? maxTokens;

  /// Nucleus sampling: limits sampling to the most probable tokens whose
  /// cumulative probability exceeds this value.
  final double? topP;

  /// Limits sampling to the [topK] most probable tokens (Google only).
  final int? topK;

  /// Sequences that stop generation once produced.
  final List<String>? stop;

  /// Penalizes repeated tokens proportionally to their frequency.
  final double? frequencyPenalty;

  /// Penalizes tokens based on whether they appeared in the prompt.
  final double? presencePenalty;

  /// Seeds the sampling for (mostly) deterministic output.
  final int? seed;

  /// Requests a structured JSON response.
  ///
  /// See [ResponseFormat] for the available modes.
  final ResponseFormat? responseFormat;

  /// The tool definitions the model may call.
  ///
  /// See [Tool] and the tool calling documentation.
  final List<Tool>? tools;

  /// Controls whether and which tool the model must call.
  ///
  /// See [ToolChoice].
  final ToolChoice? toolChoice;

  /// Additional provider-specific parameters merged into the request body.
  ///
  /// Use with care: keys here may override values generated by the provider.
  final Map<String, dynamic>? customParameters;

  /// Creates a chat completion request.
  const ChatCompletionRequest({
    required this.model,
    this.temperature,
    this.maxTokens,
    this.topP,
    this.topK,
    this.stop,
    this.frequencyPenalty,
    this.presencePenalty,
    this.seed,
    this.responseFormat,
    this.tools,
    this.toolChoice,
    this.customParameters,
  });
}
